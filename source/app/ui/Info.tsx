export function Glossary() {
  const [q, setQ] = useState('');
  const found = TERMS.filter((t) => t.join(' ').toLowerCase().includes(q.toLowerCase()));
  return (
    <>
      <div className="page-heading">
        <div>
          <span className="eyebrow">БАЗА ЗНАНИЙ</span>
          <h1>
            Деньги — понятным языком<span className="lime-dot">.</span>
          </h1>
          <p>Подсказки, к которым можно вернуться в любой момент.</p>
        </div>
        <BookOpen size={38} />
      </div>
      <label className="search-box">
        <Search size={19} />
        <input
          placeholder="Например, сложный процент"
          aria-label="Поиск по словарю"
          value={q}
          onChange={(e) => setQ(e.target.value)}
        />
        <kbd>{found.length}</kbd>
      </label>
      <div className="glossary-grid">
        {found.map(([term, description], i) => (
          <article className="panel glossary-card" key={term}>
            <span className="index-number">{String(i + 1).padStart(2, '0')}</span>
            <h3>{term}</h3>
            <p>{description}</p>
          </article>
        ))}
      </div>
      {!found.length && (
        <div className="empty-state">
          <Search size={30} />
          <h3>Термин не найден</h3>
          <p>Попробуй другое слово.</p>
        </div>
      )}
    </>
  );
}
