export const CAMPAIGN_SITUATION_IDS = Object.keys(CAMPAIGN_STORIES);

export function campaignStoryAvailable(
  id: string,
  state: import('../types').GameState,
  month: number,
) {
  const story = CAMPAIGN_STORIES[id];
  if (!story) return true;
  return (
    Math.floor(month / 12) + 1 >= story.year &&
    (story.requires !== 'car' || !!state.car) &&
    (story.requires !== 'business' || (!!state.business && !state.business.paused))
  );
}
