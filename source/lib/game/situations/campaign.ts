import type { LocationId } from '../../locations';
import type { PropKind } from '../../story-scenes';
import { rub } from '../utils';
import type { Option, Scenario } from '../types';

type Budget = 'tight' | 'steady' | 'growth' | 'wealthy';
type Choice = Option & { art: PropKind };
export type CampaignStory = {
  year: 2 | 3;
  budget: Budget;
  location: LocationId;
  requires?: 'car' | 'business';
  props: PropKind[];
  scenario: Scenario;
};
function choice(
  id: string,
  title: string,
  effects: Partial<Option>,
  explanation: string,
  art: PropKind = 'list',
): Choice {
  const details = [
    effects.cost ? `−${rub(effects.cost)}` : '',
    effects.income ? `+${rub(effects.income)}` : '',
    effects.hours ? `${effects.hours} ч` : '',
    effects.skills ? `навыки +${effects.skills}` : '',
    effects.education ? `учёба ${effects.education > 0 ? '+' : ''}${effects.education}` : '',
    effects.energy ? `ресурс ${effects.energy > 0 ? '+' : ''}${effects.energy}` : '',
    effects.safety ? `безопасность ${effects.safety > 0 ? '+' : ''}${effects.safety}` : '',
    effects.delayed?.cash && !effects.uncertainOutcome
      ? `${rub(effects.delayed.cash)} через ${effects.delayed.after} мес.`
      : '',
  ].filter(Boolean);
  return {
    id,
    title,
    ...effects,
    description: details.join(' · ') || 'Без дополнительных расходов',
    explanation,
    art,
  };
}
function story(
  year: 2 | 3,
  budget: Budget,
  location: LocationId,
  title: string,
  lead: string,
  terms: string,
  options: Choice[],
  requires?: 'car' | 'business',
): CampaignStory {
  return {
    year,
    budget,
    location,
    requires,
    props: options.map((o) => o.art),
    scenario: {
      title,
      topic: title,
      lead,
      document: { title: 'Условия', text: terms },
      options: options.map(({ art: _art, ...option }) => option),
      discussion:
        'Как выбранный вариант повлияет на расходы, время и запас денег в следующих месяцах?',
    },
  };
}

