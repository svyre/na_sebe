import type { CastId } from '../../narrative/chapters';
import type { LocationId } from '../../locations';
import type { PropKind } from '../../story-scenes';
import type { Option, Scenario } from '../types';
import { rub } from '../utils';

type FriendOption = Option & {
  say: string;
  reply: string;
  trust: -2 | -1 | 0 | 1 | 2;
  art: PropKind;
};
export type FriendSituation = {
  from: CastId;
  location: LocationId;
  scenario: Scenario;
  choices: FriendOption[];
};

function option(
  id: string,
  title: string,
  effects: Partial<Option>,
  say: string,
  reply: string,
  trust: FriendOption['trust'],
  art: PropKind,
  explanation: string,
): FriendOption {
  const details = [
    effects.cost ? `−${rub(effects.cost)}` : '',
    effects.income ? `+${rub(effects.income)}` : '',
    effects.hours ? `${effects.hours} ч` : '',
    effects.education ? `учёба +${effects.education}` : '',
    effects.skills ? `навык +${effects.skills}` : '',
    effects.energy ? `ресурс ${effects.energy > 0 ? '+' : ''}${effects.energy}` : '',
    effects.delayed?.cash ? `${rub(effects.delayed.cash)} через ${effects.delayed.after} мес.` : '',
  ].filter(Boolean);
  return {
    id,
    title,
    ...effects,
    say,
    reply,
    trust,
    art,
    explanation,
    description: details.join(' · ') || 'Без дополнительных расходов',
  };
}
function situation(
  from: CastId,
  location: LocationId,
  title: string,
  lead: string,
  terms: string,
  choices: FriendOption[],
): FriendSituation {
  return {
    from,
    location,
    choices,
    scenario: {
      title,
      topic: 'Друзья и договорённости',
      lead,
      document: { title: 'Что вы договариваетесь сделать', text: terms },
      discussion: 'Что здесь можно обещать, учитывая свой бюджет и время?',
      options: choices.map(
        ({ say: _say, reply: _reply, trust: _trust, art: _art, ...financial }) => financial,
      ),
    },
  };
}

