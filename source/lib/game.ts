export function createStorySchedule(seed:number,completed:Plan[]=[]):string[][] {
 const random=randomSource(seed),past=completed.slice(0,12).map(planSituationIds),used=new Set(past.flat());
 const pool=SITUATION_IDS.filter(id=>!used.has(id));
 for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]];}
 const schedule=[...past];let offset=0;
 for(let month=past.length;month<12;month++){const count=1+Math.floor(random()*3);schedule.push(pool.slice(offset,offset+count));offset+=count;}
 return schedule;
}
